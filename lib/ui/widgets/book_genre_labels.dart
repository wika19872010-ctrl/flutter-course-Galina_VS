// Файл русских названий жанров для отображения в интерфейсе.

import '../../domain/book.dart';

// Подписи интерфейса не меняют имена жанров, отправляемые серверу.
/// Добавляет русские названия жанров для показа в карточке и форме.
extension BookGenreLabels on BookGenre {
  // Добавляем русские подписи к перечислению жанров.
  /// Переводит жанр на русский язык.
  /// Например, fantasy — «Зарубежное фэнтези». Имена enum в базе не меняются.
  String get displayName => switch (this) {
    BookGenre.fantasy =>
      'Зарубежное фэнтези', // Сопоставляем жанр книги с русской подписью.
    BookGenre.novella =>
      'Новелла', // Сопоставляем жанр книги с русской подписью.
    BookGenre.noRomance =>
      'Нет романтики', // Сопоставляем жанр книги с русской подписью.
    BookGenre.friendship =>
      'Дружба', // Сопоставляем жанр книги с русской подписью.
  };

  /// Возвращает название жанра для формы книги.
  String get formLabel => this == BookGenre.fantasy ? 'Фэнтези' : displayName;
}
